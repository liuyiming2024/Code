-- ============================================================
-- 诱饵（canary）—— 第 ② 层：数据库层
-- ------------------------------------------------------------
-- ⚠ 红队报告指出：诱饵值**不能写死在仓库里**。
--
-- 为什么（这是本文件被推翻重写的唯一原因）：
--   上一版把诱饵值**明文写死在这里**（一个固定字符串）。
--   于是任何人打开 GitHub 都能"报出"它 ——
--   我**无法区分**他到底是不是绕过了 RLS，还是只读了公开仓库。
--   那一版的设计目的（"能读出来 = 真攻破"）**完全落空**。
--
-- ---------- 现在怎么写 ----------
-- 值在**部署时随机生成**，仓库里只有一个生成公式，没有值。
-- 部署者单独记录生成出来的值用于比对。
-- 这样"报出这个值"才真正意味着绕过了三重保护。
-- ============================================================

insert into public.oj_cred(user_id, oj, cred_enc, updated_at)
values (
  '00000000-0000-0000-0000-00000000cafe',   -- 诱饵专用 user_id，无真实用户
  'canary',
  -- ⚠ 随机值，每次执行都不同，**不出现在仓库里**
  'canary_db_' || md5(random()::text || clock_timestamp()::text),
  now()
)
on conflict (user_id, oj) do update
  set cred_enc = excluded.cred_enc, updated_at = now();

-- ---------------- 部署者：取出这次生成的值 ----------------
-- 跑完上面之后**立刻**执行下面这句，把值抄到安全的地方（别提交回仓库）：
--
--   select cred_enc from public.oj_cred
--    where user_id = '00000000-0000-0000-0000-00000000cafe';
--
-- 这个值就是第②层的比对基准。它只存在于你的数据库里。

