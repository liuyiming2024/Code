-- ============================================================
-- 诱饵（canary）—— 第 ② 层：数据库层
-- ------------------------------------------------------------
-- 在 oj_cred 表里放一行**假凭据**，属于一个**不存在的用户**。
--
-- ---------- 为什么这层才是真信号 ----------
-- 这一行受三重保护：
--   ① 表级 revoke（anon/authenticated 都没有任何权限）
--   ② RLS 已启用且**零 policy**（最严状态）
--   ③ 唯一读写口子是 security definer 函数，而函数里
--      用 auth_require() 取调用者 uid，只查 uid 自己的行
--
-- 那个假 user_id 没有任何真实用户能对应上，
-- 所以**正常路径下谁都读不到它**。
--
-- 因此：谁能读出这一行，就说明他绕过了上面三重保护 ——
-- 这是**真正的攻破**，比第 ① 层（公开仓库）有意义得多。
--
-- ---------- 怎么用 ----------
--   1. 跑一次本文件（建诱饵行）
--   2. 让对方尝试读取
--   3. 让他报出他看到的 cred_enc 内容
--   4. 如果内容 == 下面的诱饵值 → **RLS 或函数门禁被绕过了**
--   5. 测完执行文件末尾的清理语句删掉它
-- ============================================================

insert into public.oj_cred(user_id, oj, cred_enc, updated_at)
values (
  '00000000-0000-0000-0000-00000000cafe',   -- 诱饵专用 user_id，无真实用户
  'canary',
  'canary_db_测试密钥_do_not_use_0002',      -- 诱饵值；注意它不是合法 enc1: 密文
  now()
)
on conflict (user_id, oj) do update
  set cred_enc = excluded.cred_enc, updated_at = now();

